//! Writes `COMPATIBILITY.md` from the harness results in `target/compat-*.tsv` and from
//! `allowlist.toml`. Run after `cargo test -p oxilite-compat`.
//!
// @lat: [[test-plan#Oxigraph compatibility harness#Allow-list and report]]

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

fn last_by_suite(path: &Path) -> BTreeMap<String, Vec<String>> {
    let mut out = BTreeMap::new();
    if let Ok(text) = std::fs::read_to_string(path) {
        for line in text.lines() {
            let cols: Vec<String> = line.split('\t').map(String::from).collect();
            if let Some((suite, rest)) = cols.split_first() {
                out.insert(suite.clone(), rest.to_vec());
            }
        }
    }
    out
}

fn short(suite: &str) -> String {
    suite
        .replace("https://w3c.github.io/rdf-tests/", "W3C ")
        .replace("https://github.com/oxigraph/oxigraph/tests/", "Oxigraph ")
        .replace("/manifest.ttl", "")
        .replace(".ttl", "")
}

fn main() -> anyhow::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let report = last_by_suite(&root.join("target/compat-report.tsv"));
    let coverage = last_by_suite(&root.join("target/compat-coverage.tsv"));
    let allow = oxilite_compat::allowlist::load()?;
    let mut md = String::from(
        "# Compatibility report\n\nGenerated by `cargo run -p oxilite-compat --bin compat-report` from the \
compatibility harness (`testsuite/`): Oxigraph's W3C test runner and store tests run on every oxilite \
variant (rusqlite with and without statistics, SQLite planner, dlopen'ed system SQLite), plus a \
differential corpus compared with Oxigraph. See `lat.md/test-plan.md`.\n\n\
## Test suites\n\n| suite | tests | passed | failing upstream (Oxigraph baseline) | allow-listed | unexpected |\n|---|---|---|---|---|---|\n",
    );
    for (suite, c) in &report {
        let _ = writeln!(md, "| {} | {} |", short(suite), c.join(" | "));
    }
    md.push_str("\n## Evaluations compiled to SQL\n\nHow many oxilite query evaluations ran entirely as SQL, versus partly through the spareval fallback (all variants counted; the dylib variant has no UDFs).\n\n| suite | fully SQL | with fallback | share |\n|---|---|---|---|\n");
    for (suite, c) in &coverage {
        let (a, b): (f64, f64) = (c[0].parse().unwrap_or(0.0), c[1].parse().unwrap_or(0.0));
        let _ = writeln!(
            md,
            "| {} | {} | {} | {:.1}% |",
            short(suite),
            c[0],
            c[1],
            100.0 * a / (a + b).max(1.0)
        );
    }
    md.push_str("\n## Accepted divergences\n\n| id | reason | decision |\n|---|---|---|\n");
    let mut entries: Vec<_> = allow.iter().collect();
    entries.sort_by_key(|(k, _)| (*k).clone());
    for (id, e) in entries {
        let _ = writeln!(md, "| `{id}` | {} | {} |", e.reason, e.decision);
    }
    std::fs::write(root.join("COMPATIBILITY.md"), md)?;
    println!("wrote COMPATIBILITY.md");
    Ok(())
}
